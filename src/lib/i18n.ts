const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS
};

const localeOptions: Array<{ value: Locale; labelKey: TranslationKey }> = [
  { value: "zh-CN", labelKey: "locale.zhCN" },
  { value: "en-US", labelKey: "locale.enUS" }
];

const listeners = new Set<() => void>();
let currentLocale = loadLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(LOCALE_KEY, locale);
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
  }
  listeners.forEach((listener) => listener());
}

export function translate(key: TranslationKey, values: TranslationValues = {}, locale = currentLocale): string {
  const template = dictionaries[locale]?.[key] ?? enUS[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined || value === null ? match : String(value);
  });
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribe, getLocale, getLocale);
  return {
    locale,
    localeOptions,
    setLocale,
    t: (key: TranslationKey, values?: TranslationValues) => translate(key, values, locale)
  };
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function loadLocale(): Locale {
  if (typeof localStorage === "undefined") {
    return "zh-CN";
  }
  return normalizeLocale(localStorage.getItem(LOCALE_KEY));
}

function normalizeLocale(value: unknown): Locale {
  return value === "en-US" ? "en-US" : "zh-CN";
}
